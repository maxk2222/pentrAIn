import { useEffect, useRef, useState } from "react";
import { Terminal } from "@xterm/xterm";
import { FitAddon } from "@xterm/addon-fit";
import { WebLinksAddon } from "@xterm/addon-web-links";
import { ClipboardPaste, RefreshCw } from "lucide-react";
import { wsUrl } from "@/lib/api";
import "@xterm/xterm/css/xterm.css";
import kaliDragon from "@/assets/kali-dragon.svg";

/** Connection state shown as a chip on the tab and as an overlay hint. */
export type TermState = "connecting" | "waiting" | "live" | "exited" | "closed";

const enc = new TextEncoder();

async function copyText(t: string) {
  try {
    await navigator.clipboard.writeText(t);
  } catch {
    // http://LAN deployments aren't a secure context — execCommand fallback
    const ta = document.createElement("textarea");
    ta.value = t;
    ta.style.cssText = "position:fixed;opacity:0";
    document.body.appendChild(ta);
    ta.select();
    try { document.execCommand("copy"); } catch { /* best effort */ }
    ta.remove();
  }
}

/** xterm.js browser terminal — pairs with the backend's kali reverse-channel.
 *  The chan id is generated by the parent and persisted, so a reconnect /
 *  page reload re-attaches to the same tmux session on kali.
 *  Mounts hidden OK: the socket only opens once the view is visible, so a
 *  background tab never measures a collapsed (display:none) container. */
export function TerminalView({ sessionId, chan, visible = true, onStatus }: {
  sessionId: number;
  chan: string;
  visible?: boolean;
  onStatus?: (s: TermState) => void;
}) {
  const hostRef = useRef<HTMLDivElement>(null);
  const termRef = useRef<Terminal | null>(null);
  const fitRef = useRef<FitAddon | null>(null);
  const wsRef = useRef<WebSocket | null>(null);
  const retriesRef = useRef(0);
  const onStatusRef = useRef(onStatus);
  const [state, setState] = useState<TermState>("connecting");
  const stateRef = useRef<TermState>("connecting");
  const unmountedRef = useRef(false);
  onStatusRef.current = onStatus;

  function setTermState(s: TermState) {
    stateRef.current = s;
    setState(s);
    onStatusRef.current?.(s);
  }

  function sendResize() {
    const dims = fitRef.current?.proposeDimensions();
    const ws = wsRef.current;
    if (dims && ws?.readyState === WebSocket.OPEN) {
      ws.send(JSON.stringify({ t: "resize", cols: dims.cols, rows: dims.rows }));
    }
  }

  function connect() {
    const term = termRef.current, fit = fitRef.current;
    if (!term || !fit || unmountedRef.current) return;
    const ws0 = wsRef.current;
    if (ws0 && ws0.readyState <= WebSocket.OPEN) return; // already connecting/open
    const dims = fit.proposeDimensions() ?? { cols: 120, rows: 32 };
    setTermState("connecting");
    const ws = new WebSocket(wsUrl(
      `/api/terminal/${sessionId}/${chan}?cols=${dims.cols}&rows=${dims.rows}`));
    ws.binaryType = "arraybuffer";
    wsRef.current = ws;

    ws.onopen = () => {
      retriesRef.current = 0;   // a live connection resets the retry budget —
      sendResize();             // otherwise 5 lifetime drops kill the tab
    };
    ws.onmessage = (e) => {
      if (typeof e.data === "string") {
        try {
          const ctl = JSON.parse(e.data);
          if (ctl.t === "status") { setTermState(ctl.state as TermState); return; }
          if (ctl.t === "exit") {
            setTermState("exited");
            term.writeln(`\r\n\x1b[90m[shell exited — code ${ctl.code}]\x1b[0m`);
            return;
          }
        } catch { /* not control — ignore */ }
        return;
      }
      term.write(new Uint8Array(e.data as ArrayBuffer));
    };
    ws.onclose = () => {
      if (stateRef.current === "closed" || unmountedRef.current) return;
      if (retriesRef.current++ < 5) {
        setTermState("connecting");
        setTimeout(() => {
          if (!unmountedRef.current && stateRef.current !== "closed") connect();
        }, 2500);
      } else {
        setTermState("closed");
      }
    };
    ws.onerror = () => ws.close();
  }

  // mount once per component instance (parent keys by chan) — stable across
  // parent re-renders; only the first visibility builds the socket so a
  // hidden tab never measures a collapsed container.
  useEffect(() => {
    const host = hostRef.current;
    if (!host) return;
    unmountedRef.current = false;
    const term = new Terminal({
      allowTransparency: true,
      cursorBlink: true,
      cursorStyle: "bar",
      fontFamily: '"JetBrains Mono", "Fira Code", "SF Mono", Menlo, monospace',
      fontSize: 13,
      lineHeight: 1.15,
      letterSpacing: 0.2,
      scrollback: 5000,
      theme: {
        background: "rgba(10, 14, 20, 0.55)",
        foreground: "#e6edf6",
        cursor: "#22d3ee",
        cursorAccent: "#0a0e14",
        selectionBackground: "rgba(34, 211, 238, 0.28)",
        black: "#0a0e14",
        brightBlack: "#4b5a70",
      },
    });
    const fit = new FitAddon();
    term.loadAddon(fit);
    term.loadAddon(new WebLinksAddon());
    term.open(host);
    termRef.current = term;
    fitRef.current = fit;
    fit.fit();

    term.attachCustomKeyEventHandler((e) => {
      if (e.type !== "keydown") return true;
      const mod = e.ctrlKey || e.metaKey;
      const key = e.key.toLowerCase();
      if (mod && key === "c") {
        // smart copy: selection → clipboard, no selection → SIGINT passes
        if (term.hasSelection()) {
          copyText(term.getSelection());
          term.clearSelection();
          return false;
        }
        return true;
      }
      if (mod && e.shiftKey && key === "v" && navigator.clipboard?.readText) {
        navigator.clipboard.readText()
          .then((t) => { if (t) term.paste(t); })
          .catch(() => {});
        return false;
      }
      // plain paste (Cmd+V / Ctrl+V): xterm's hidden textarea handles it
      // natively and pipes through onData — works without clipboard API too
      return true;
    });

    term.onData((d) => {
      const ws = wsRef.current;
      if (ws?.readyState === WebSocket.OPEN) ws.send(enc.encode(d));
    });

    if (visible) connect();
    const ro = new ResizeObserver(() => { fit.fit(); sendResize(); });
    ro.observe(host);
    return () => {
      unmountedRef.current = true;
      ro.disconnect();
      stateRef.current = "closed";
      wsRef.current?.close();
      term.dispose();
      termRef.current = null;
      wsRef.current = null;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [sessionId, chan]);

  // on becoming visible: measure properly, open the socket if needed
  useEffect(() => {
    if (visible) {
      fitRef.current?.fit();
      sendResize();
      connect();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [visible]);

  return (
    <div className="relative h-full w-full overflow-hidden bg-[#0a0e14]">
      {/* kali watermark behind the transparent terminal */}
      <img src={kaliDragon} alt="" aria-hidden
        className="pointer-events-none absolute inset-0 m-auto w-56 select-none opacity-[0.06]" />
      <div ref={hostRef} className="pentrain-term h-full w-full px-1.5 py-1" />

      {/* floating paste button — needed when the browser blocks Cmd/V paste */}
      <button
        title="Paste from clipboard (or Cmd/Ctrl+V)"
        onClick={() => navigator.clipboard?.readText()
          .then((t) => { if (t) termRef.current?.paste(t); })
          .catch(() => {})}
        className="absolute right-2 top-2 rounded border border-border/60 bg-surface/70 p-1
          text-muted opacity-40 transition hover:opacity-100">
        <ClipboardPaste className="h-3.5 w-3.5" />
      </button>

      {state !== "live" && (
        <div className="absolute inset-x-0 bottom-0 flex items-center justify-center gap-2
          border-t border-border/50 bg-background/80 px-3 py-1.5 text-xs text-muted backdrop-blur">
          {state === "connecting" && <span>connecting…</span>}
          {state === "waiting" && <span>waiting for kali agent…</span>}
          {state === "exited" && <span>shell exited</span>}
          {state === "closed" && <span>connection closed</span>}
          {(state === "closed" || state === "exited") && (
            <button onClick={() => { retriesRef.current = 0; connect(); }}
              className="flex items-center gap-1 rounded border border-border px-1.5 py-0.5
                text-foreground hover:bg-surface-2">
              <RefreshCw className="h-3 w-3" /> reconnect
            </button>
          )}
        </div>
      )}
    </div>
  );
}
